import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

const base = 'http://127.0.0.1:19861';
const backend = 'http://127.0.0.1:19862';
const dir = path.resolve(process.env.PULSE_ARTIFACT_DIR || '../../artifacts/tech/office');
await fs.mkdir(dir, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ locale: 'ru-RU', viewport: { width: 1440, height: 1000 }, recordVideo: { dir: path.join(dir, 'raw'), size: { width: 1440, height: 1000 } } });
const page = await context.newPage();
const started = Date.now();
const evidence = { errors: [], checks: [], timings: {} };
page.on('pageerror', (error) => evidence.errors.push(error.message));
const mark = (name) => { evidence.timings[name] = (Date.now() - started) / 1000; console.log(name); };
const state = async () => (await page.request.get(`${backend}/state`, { headers: { Origin: base } })).json();
try {
  await page.goto(`${base}/tech/office`);
  await expect(page.locator('.office-flow .react-flow__node')).toHaveCount(8);
  await page.waitForTimeout(1500); mark('start');
  await page.getByRole('button', { name: 'Начать наблюдение' }).click();
  await expect(page.getByRole('log')).toContainText('Проверяю учебный почтовый ящик');
  await page.waitForTimeout(2000); mark('mail');
  await page.getByRole('button', { name: 'Получить учебное письмо' }).click();
  await expect(page.getByRole('button', { name: 'Подтвердить изменения' })).toBeVisible({ timeout: 60000 });
  const pending = await state();
  expect(pending.status).toBe('waiting_approval');
  expect(pending.results).toEqual({});
  expect(await (await page.request.get(`${backend}/site`)).text()).toContain('Новая услуга ещё не опубликована');
  mark('approval');
  await page.waitForTimeout(1800);
  await page.locator('.office-flow [data-id="approval"]').click();
  await page.waitForTimeout(1800);
  await page.screenshot({ path: path.join(dir, 'approval.png') });
  mark('confirm');
  await page.getByRole('button', { name: 'Подтвердить изменения' }).click();
  await expect(page.getByRole('status')).toContainText('Результаты сохранены');
  const complete = await state();
  expect(complete.status).toBe('completed');
  expect(complete.results.website.title).toMatch(/аудит/iu);
  expect(complete.results.invoice.amount_minor).toBe(4500000);
  expect(complete.results.invoice.bank_connected).toBe(false);
  const calls = complete.events.filter(event => event.usage);
  expect(calls.length).toBe(2);
  expect(calls.every(event => event.usage.input_tokens > 0 && event.usage.output_tokens > 0)).toBeTruthy();
  mark('result'); await page.waitForTimeout(2600);
  await page.locator('.office-flow [data-id="done"]').click();
  await page.screenshot({ path: path.join(dir, 'result.png') });
  mark('graph'); await page.waitForTimeout(3200); mark('end');
  await page.reload();
  await expect(page.getByLabel('Сохранённые результаты')).toContainText('45 000');
  const website = await (await page.request.get(`${backend}/site`)).text();
  expect(website).toContain(complete.results.website.title);
  expect(website).not.toContain('Новая услуга ещё не опубликована');
  const repeat = await page.request.post(`${backend}/decision`, { headers: { Origin: base }, data: { approve: true } });
  expect(repeat.status()).toBe(409);
  expect((await state()).results).toEqual(complete.results);
  const denied = await page.request.post(`${backend}/decision`, { headers: { Origin: 'https://example.test' }, data: { approve: true } });
  expect(denied.status()).toBe(403);
  evidence.checks.push('No site or invoice writes before approval', 'Two real model responses with usage', 'Website and invoice persisted after approval', 'Duplicate decision rejected', 'Untrusted origin rejected');
  evidence.recording = complete;
  expect(evidence.errors).toEqual([]);
} catch (error) {
  evidence.failure = error.message;
  evidence.lastState = await state();
  await page.screenshot({ path: path.join(dir, 'error.png') });
  process.exitCode = 1;
} finally {
  await context.close();
  await fs.copyFile(await page.video().path(), path.join(dir, 'office.webm'));
  await fs.writeFile(path.join(dir, 'evidence.json'), JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify({ checks: evidence.checks, failure: evidence.failure, timings: evidence.timings }));
  await browser.close();
}
