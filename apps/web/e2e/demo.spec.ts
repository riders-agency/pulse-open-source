import { expect, test } from "@playwright/test";
import { writeFile } from "node:fs/promises";
const base = process.env.PULSE_BASE_URL || "http://127.0.0.1:19871";

test("demo company runs its mailbox workflow, waits for a human and preserves history", async ({ browser }) => {
  test.setTimeout(240_000);
  const first = await browser.newContext({ viewport: { width: 1440, height: 1000 }, recordVideo: { dir: "../../artifacts/office-native", size: { width: 1440, height: 1000 } } });
  const second = await browser.newContext();
  try {
    const page = await first.newPage();
    const recordingStarted = Date.now();
    const timings: Record<string, number> = {};
    const mark = (name: string) => { timings[name] = (Date.now() - recordingStarted) / 1000; };
    const hold = async (ms: number) => { if (process.env.PULSE_RECORD_DEMO === "1") await page.waitForTimeout(ms); };
    let registrations = 0;
    page.on("request", (request) => { if (request.method() === "POST" && request.url().endsWith("/api/v1/auth/register")) registrations++; });
    await page.goto(`${base}/project-workflows?demo=1`);
    await expect(page).toHaveURL(/\/project-workflows$/, { timeout: 45000 });
    await expect(page.getByRole("heading", { name: "Почта → работа ИИ-отделов" })).toBeVisible();
    await expect(page.locator("iframe")).toHaveCount(0);
    await expect(page.getByText("Опрос каждые 30 секунд", { exact: true })).toBeVisible();
    mark("start"); await hold(4000);
    const project = await page.evaluate(() => sessionStorage.getItem("pulse-demo-context"));
    expect(project).toBeTruthy();
    const origin = new URL(page.url()).origin;
    const csrf = (await first.cookies(origin)).find((cookie) => cookie.name === "rp_csrf")?.value || "";
    const headers = { "X-CSRF-Token": csrf };
    const stateUrl = `${origin}/api/v1/projects/${project}/office-demo`;
    const state = await (await page.request.get(stateUrl)).json();
    const runsUrl = `${origin}/api/v1/workflows/${state.workflow_id}/runs`;
    let runs: { workflow_run_id: string; status: string }[] = [];
    await expect.poll(async () => { runs = await (await page.request.get(runsUrl)).json(); return runs[0]?.status; }, { timeout: 75000, intervals: [2000] }).toBe("waiting");
    const run = runs[0].workflow_run_id;
    expect((await (await page.request.get(stateUrl)).json()).artifacts).toHaveLength(0);
    await page.getByRole("link", { name: "История исполнений", exact: true }).click();
    await expect(page.getByText("Ждёт решения", { exact: true })).toBeVisible();
    await page.getByRole("link", { name: "Карта выполнения", exact: true }).first().click();
    await expect(page.getByRole("button", { name: "Подтвердить изменения" })).toBeVisible();
    await expect(page.getByRole("region", { name: "Расход модели" })).toContainText("2 вызова");
    await expect(page.getByText("Действие завершилось с ошибкой.", { exact: true })).toHaveCount(0);
    await expect(page.locator(".react-flow__node")).toHaveCount(7);
    await page.screenshot({ path: "../../artifacts/tech/office-native-approval.png", fullPage: true });
    const prepared = await (await page.request.get(`${origin}/api/v1/runs/${run}/actions`)).json();
    const preparedPage = prepared.find((action: { action_key: string }) => action.action_key === "website");
    mark("approval"); await hold(4000);
    await page.getByRole("button", { name: "Подтвердить изменения" }).click();
    await expect.poll(async () => (await (await page.request.get(`${origin}/api/v1/runs/${run}`)).json()).status, { timeout: 20000 }).toBe("succeeded");
    mark("confirmed"); await hold(3500);
    const after = await (await page.request.get(stateUrl)).json();
    expect(after.artifacts).toHaveLength(1);
    expect(after.artifacts[0].invoice_json.status).toBe("draft");
    expect(after.artifacts[0].page_json).toEqual(preparedPage.output_json.result);
    const resumed = await (await page.request.get(`${origin}/api/v1/runs/${run}/actions`)).json();
    expect(resumed.find((action: { action_key: string }) => action.action_key === "website").provider_response_json).toEqual(preparedPage.provider_response_json);
    const events = await (await page.request.get(`${origin}/api/v1/runs/${run}/events`)).json();
    expect(events.filter((event: { event_type: string; action_key: string }) => event.event_type === "action.started" && ["classify", "website"].includes(event.action_key))).toHaveLength(2);
    const duplicate = await page.request.post(`${stateUrl}/decisions/${run}`, { headers, data: { approved: true } });
    expect(duplicate.status()).toBe(409);
    await page.goto(`${origin}/project-workflows`);
    await expect(page.getByRole("heading", { name: "Почта → работа ИИ-отделов" })).toBeVisible();
    await page.getByText("Результаты в демо-компании (1)", { exact: true }).click();
    mark("results"); await hold(4000); mark("end");
    await page.getByText("Результаты в демо-компании (1)", { exact: true }).click();
    const delivered = page.waitForRequest((request) => request.method() === "POST" && request.url() === `${stateUrl}/messages`);
    await page.getByRole("button", { name: "Добавить учебное письмо" }).click();
    const request = await delivered;
    expect((await page.request.post(`${stateUrl}/messages`, { headers, data: request.postDataJSON() })).ok()).toBe(true);
    await expect.poll(async () => { runs = await (await page.request.get(runsUrl)).json(); return runs.find((item) => item.workflow_run_id !== run)?.status; }, { timeout: 75000, intervals: [2000] }).toBe("waiting");
    expect(runs).toHaveLength(2);
    const rejectedRun = runs.find((item) => item.workflow_run_id !== run)!.workflow_run_id;
    await page.goto(`${origin}/runs/${rejectedRun}`);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole("button", { name: "Отклонить", exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(2);
    expect(await page.locator(".runtime-canvas .react-flow").evaluate((el) => el.getBoundingClientRect().height)).toBeGreaterThan(300);
    await page.screenshot({ path: "../../artifacts/tech/office-native-graph-mobile.png", fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole("button", { name: "Отклонить", exact: true }).click();
    await expect.poll(async () => (await (await page.request.get(`${origin}/api/v1/runs/${rejectedRun}`)).json()).status, { timeout: 20000 }).toBe("succeeded");
    expect((await (await page.request.get(stateUrl)).json()).artifacts).toHaveLength(1);
    await page.goto(`${origin}/demo?start=1`);
    await expect(page).toHaveURL(`${origin}/project-workflows`);
    expect(await page.evaluate(() => sessionStorage.getItem("pulse-demo-context"))).toBe(project);
    expect(registrations).toBe(1);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole("heading", { name: "Почта → работа ИИ-отделов" })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(2);
    await page.screenshot({ path: "../../artifacts/tech/office-native-mobile.png", fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByText("Результаты в демо-компании (1)", { exact: true }).click();
    await page.screenshot({ path: "../../artifacts/tech/office-native-desktop.png", fullPage: true });
    const visitor = await second.newPage();
    await visitor.goto(`${origin}/project-workflows?demo=1`);
    await expect(visitor).toHaveURL(`${origin}/project-workflows`, { timeout: 45000 });
    expect((await visitor.request.get(stateUrl)).status()).toBe(403);
    const denied = await page.request.post(`${origin}/api/v1/projects/${project}/action-dependencies`, { headers, data: {} });
    expect(denied.status()).toBe(403);
    await writeFile("../../artifacts/office-native/evidence.json", JSON.stringify({ timings, video: await page.video()?.path(), origin, project, workflow: state.workflow_id, approvedRun: run, rejectedRun, pollCount: after.poll_count, runCount: runs.length, retainedRuns: after.retained_runs, artifacts: after.artifacts.length }, null, 2));
  } finally { await first.close(); await second.close(); }
});
