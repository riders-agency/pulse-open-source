package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
)

const (
	beginMarker = "  # BEGIN generated runtime inventory paths"
	endMarker   = "  # END generated runtime inventory paths"
)

type inventoryRow struct {
	Method      string
	Path        string
	Module      string
	OperationID string
}

func main() {
	inventoryPath := flag.String("inventory", "../../contracts/openapi/endpoints.inventory.tsv", "endpoint inventory TSV")
	rootPath := flag.String("root", "../../contracts/openapi/openapi.root.yaml", "OpenAPI root YAML")
	modulePath := flag.String("module", "../../contracts/openapi/modules/runtime-inventory.generated.yaml", "generated runtime inventory module")
	flag.Parse()

	rootRaw, err := os.ReadFile(*rootPath)
	if err != nil {
		fail("read root: %v", err)
	}
	existing := rootPaths(string(rootRaw))
	rows, err := readInventory(*inventoryPath)
	if err != nil {
		fail("read inventory: %v", err)
	}

	missingByPath := map[string][]inventoryRow{}
	for _, row := range rows {
		if _, ok := existing[row.Path]; ok {
			continue
		}
		missingByPath[row.Path] = append(missingByPath[row.Path], row)
	}

	if err := os.WriteFile(*modulePath, buildModule(missingByPath), 0o644); err != nil {
		fail("write module: %v", err)
	}
	nextRoot, err := syncRootRefs(string(rootRaw), missingByPath)
	if err != nil {
		fail("sync root refs: %v", err)
	}
	if err := os.WriteFile(*rootPath, []byte(nextRoot), 0o644); err != nil {
		fail("write root: %v", err)
	}
	fmt.Printf("OpenAPI runtime inventory supplement synced: paths=%d operations=%d\n", len(missingByPath), countOperations(missingByPath))
}

func readInventory(path string) ([]inventoryRow, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	var rows []inventoryRow
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) < 4 {
			return nil, fmt.Errorf("invalid inventory row %q", line)
		}
		rows = append(rows, inventoryRow{
			Method:      strings.ToUpper(strings.TrimSpace(parts[0])),
			Path:        normalizePath(parts[1]),
			Module:      strings.TrimSpace(parts[2]),
			OperationID: strings.TrimSpace(parts[3]),
		})
	}
	return rows, scanner.Err()
}

func rootPaths(root string) map[string]struct{} {
	paths := map[string]struct{}{}
	inGeneratedBlock := false
	scanner := bufio.NewScanner(strings.NewReader(root))
	for scanner.Scan() {
		line := scanner.Text()
		if line == beginMarker {
			inGeneratedBlock = true
			continue
		}
		if line == endMarker {
			inGeneratedBlock = false
			continue
		}
		if inGeneratedBlock {
			continue
		}
		if strings.HasPrefix(line, "  /") {
			paths[strings.TrimSuffix(strings.TrimSpace(line), ":")] = struct{}{}
		}
	}
	return paths
}

func buildModule(rowsByPath map[string][]inventoryRow) []byte {
	var out bytes.Buffer
	out.WriteString("# Code generated by apps/api/cmd/sync-openapi-inventory; DO NOT EDIT.\n")
	out.WriteString("paths:\n")
	for _, path := range sortedKeys(rowsByPath) {
		out.WriteString("  " + path + ":\n")
		rows := rowsByPath[path]
		sort.Slice(rows, func(i, j int) bool {
			return rows[i].Method < rows[j].Method
		})
		for _, row := range rows {
			out.WriteString("    " + strings.ToLower(row.Method) + ":\n")
			out.WriteString("      tags: [" + yamlScalar(row.Module) + "]\n")
			out.WriteString("      operationId: " + yamlScalar(row.OperationID) + "\n")
			out.WriteString("      summary: Runtime inventory operation " + yamlScalar(row.OperationID) + "\n")
			out.WriteString("      x-runtime-source: endpoints.inventory.tsv\n")
			writePathParameters(&out, pathParams(row.Path))
			out.WriteString("      responses:\n")
			out.WriteString("        '200':\n")
			out.WriteString("          description: Runtime response\n")
			out.WriteString("        '400':\n")
			out.WriteString("          description: Problem response\n")
		}
	}
	return out.Bytes()
}

func writePathParameters(out *bytes.Buffer, params []string) {
	if len(params) == 0 {
		return
	}
	out.WriteString("      parameters:\n")
	for _, param := range params {
		out.WriteString("        - name: " + yamlScalar(param) + "\n")
		out.WriteString("          in: path\n")
		out.WriteString("          required: true\n")
		out.WriteString("          schema:\n")
		out.WriteString("            type: string\n")
	}
}

func pathParams(path string) []string {
	var params []string
	seen := map[string]struct{}{}
	remaining := path
	for {
		start := strings.Index(remaining, "{")
		if start < 0 {
			return params
		}
		remaining = remaining[start+1:]
		end := strings.Index(remaining, "}")
		if end < 0 {
			return params
		}
		param := strings.TrimSpace(remaining[:end])
		if param != "" {
			if _, ok := seen[param]; !ok {
				params = append(params, param)
				seen[param] = struct{}{}
			}
		}
		remaining = remaining[end+1:]
	}
}

func syncRootRefs(root string, rowsByPath map[string][]inventoryRow) (string, error) {
	block := buildRootBlock(rowsByPath)
	lines := strings.Split(root, "\n")
	begin, end := -1, -1
	for i, line := range lines {
		if line == beginMarker {
			begin = i
		}
		if line == endMarker {
			end = i
			break
		}
	}
	if begin >= 0 || end >= 0 {
		if begin < 0 || end < begin {
			return "", fmt.Errorf("invalid generated marker block")
		}
		next := append([]string{}, lines[:begin]...)
		next = append(next, strings.Split(strings.TrimSuffix(block, "\n"), "\n")...)
		next = append(next, lines[end+1:]...)
		return strings.Join(next, "\n"), nil
	}
	components := -1
	for i, line := range lines {
		if line == "components:" {
			components = i
			break
		}
	}
	if components < 0 {
		return "", fmt.Errorf("components marker not found")
	}
	next := append([]string{}, lines[:components]...)
	next = append(next, strings.Split(strings.TrimSuffix(block, "\n"), "\n")...)
	next = append(next, lines[components:]...)
	return strings.Join(next, "\n"), nil
}

func buildRootBlock(rowsByPath map[string][]inventoryRow) string {
	var out strings.Builder
	out.WriteString(beginMarker + "\n")
	for _, path := range sortedKeys(rowsByPath) {
		out.WriteString("  " + path + ":\n")
		out.WriteString("    $ref: ./modules/runtime-inventory.generated.yaml#/paths/" + jsonPointer(path) + "\n")
	}
	out.WriteString(endMarker + "\n")
	return out.String()
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func normalizePath(path string) string {
	path = strings.TrimSpace(path)
	if path == "" {
		return "/"
	}
	if !strings.HasPrefix(path, "/") {
		path = "/" + path
	}
	if len(path) > 1 {
		path = strings.TrimSuffix(path, "/")
	}
	return path
}

func jsonPointer(path string) string {
	path = strings.ReplaceAll(path, "~", "~0")
	return strings.ReplaceAll(path, "/", "~1")
}

func yamlScalar(value string) string {
	if value == "" {
		return "unknown"
	}
	return value
}

func countOperations(rowsByPath map[string][]inventoryRow) int {
	var count int
	for _, rows := range rowsByPath {
		count += len(rows)
	}
	return count
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
