package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	yaml "gopkg.in/yaml.v3"
)

type operation struct {
	Method      string
	Path        string
	OperationID string
}

func main() {
	openapiPath := flag.String("openapi", "../../contracts/openapi/dist/openapi.yaml", "bundled OpenAPI YAML")
	outputPath := flag.String("output", "../web/src/lib/api/generated/openapi-client.ts", "generated web client output")
	flag.Parse()

	ops, err := readOperations(*openapiPath)
	if err != nil {
		fail("read operations: %v", err)
	}
	if len(ops) == 0 {
		fail("no OpenAPI operations found")
	}
	if err := os.MkdirAll(filepath.Dir(*outputPath), 0o755); err != nil {
		fail("create output directory: %v", err)
	}
	if err := os.WriteFile(*outputPath, renderClient(ops), 0o644); err != nil {
		fail("write generated client: %v", err)
	}
	fmt.Printf("OpenAPI web client generated: operations=%d path=%s\n", len(ops), *outputPath)
}

func readOperations(path string) ([]operation, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc map[string]any
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	var ops []operation
	for rawPath, rawPathItem := range asMap(doc["paths"]) {
		pathItem := asMap(rawPathItem)
		for rawMethod, rawOperation := range pathItem {
			method := strings.ToUpper(strings.TrimSpace(rawMethod))
			if !isHTTPMethod(method) {
				continue
			}
			operationID := stringValue(asMap(rawOperation)["operationId"])
			if operationID == "" {
				return nil, fmt.Errorf("missing operationId method=%s path=%s", method, rawPath)
			}
			ops = append(ops, operation{
				Method:      method,
				Path:        rawPath,
				OperationID: operationID,
			})
		}
	}
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].OperationID == ops[j].OperationID {
			if ops[i].Path == ops[j].Path {
				return ops[i].Method < ops[j].Method
			}
			return ops[i].Path < ops[j].Path
		}
		return ops[i].OperationID < ops[j].OperationID
	})
	seen := map[string]operation{}
	for _, op := range ops {
		if prev, ok := seen[op.OperationID]; ok {
			return nil, fmt.Errorf("duplicate operationId %s for %s %s and %s %s", op.OperationID, prev.Method, prev.Path, op.Method, op.Path)
		}
		seen[op.OperationID] = op
	}
	return ops, nil
}

func renderClient(ops []operation) []byte {
	var out bytes.Buffer
	out.WriteString("/**\n")
	out.WriteString(" * This file was auto-generated by apps/api/cmd/gen-openapi-web-client.\n")
	out.WriteString(" * Do not make direct changes to the file.\n")
	out.WriteString(" */\n\n")
	out.WriteString("import type { operations, paths } from \"./openapi-types\";\n\n")
	out.WriteString("export type OpenAPIHttpMethod = \"DELETE\" | \"GET\" | \"PATCH\" | \"POST\" | \"PUT\";\n")
	out.WriteString("export type OpenAPIPath = keyof paths;\n")
	out.WriteString("export type OpenAPIOperationId = keyof operations;\n\n")
	out.WriteString("export const openAPIOperations = {\n")
	for _, op := range ops {
		out.WriteString("    ")
		out.WriteString(quote(op.OperationID))
		out.WriteString(": { method: ")
		out.WriteString(quote(op.Method))
		out.WriteString(", path: ")
		out.WriteString(quote(op.Path))
		out.WriteString(" },\n")
	}
	out.WriteString("} as const satisfies Record<OpenAPIOperationId, { method: OpenAPIHttpMethod; path: OpenAPIPath }>;\n\n")
	out.WriteString("export type OpenAPIClientParameters<ID extends OpenAPIOperationId> = operations[ID] extends { parameters: infer Params } ? Params : never;\n")
	out.WriteString("export type OpenAPIClientRequestBody<ID extends OpenAPIOperationId> = operations[ID] extends { requestBody: { content: { \"application/json\": infer Body } } } ? Body : never;\n")
	out.WriteString("type OpenAPIResponseContent<Response> = Response extends { content: { \"application/json\": infer Body } } ? Body : Response extends { content: { \"text/javascript\": infer Body } } ? Body : Response extends { content: { \"text/yaml\": infer Body } } ? Body : unknown;\n")
	out.WriteString("type OpenAPIResponses<ID extends OpenAPIOperationId> = operations[ID] extends { responses: infer Responses } ? Responses : never;\n")
	out.WriteString("export type OpenAPIClientResponse<ID extends OpenAPIOperationId> =\n")
	out.WriteString("    OpenAPIResponses<ID> extends { 200: infer Response } ? OpenAPIResponseContent<Response> :\n")
	out.WriteString("    OpenAPIResponses<ID> extends { 201: infer Response } ? OpenAPIResponseContent<Response> :\n")
	out.WriteString("    OpenAPIResponses<ID> extends { 202: infer Response } ? OpenAPIResponseContent<Response> :\n")
	out.WriteString("    OpenAPIResponses<ID> extends { 204: infer Response } ? OpenAPIResponseContent<Response> :\n")
	out.WriteString("    OpenAPIResponses<ID> extends { 101: infer Response } ? OpenAPIResponseContent<Response> : unknown;\n\n")
	out.WriteString("export type OpenAPIClientInput<ID extends OpenAPIOperationId> = {\n")
	out.WriteString("    params?: OpenAPIClientParameters<ID>;\n")
	out.WriteString("    body?: OpenAPIClientRequestBody<ID>;\n")
	out.WriteString("    headers?: Record<string, string>;\n")
	out.WriteString("};\n\n")
	out.WriteString("export type OpenAPIClientTransportInput<ID extends OpenAPIOperationId> = OpenAPIClientInput<ID> & {\n")
	out.WriteString("    operationId: ID;\n")
	out.WriteString("    method: (typeof openAPIOperations)[ID][\"method\"];\n")
	out.WriteString("    path: (typeof openAPIOperations)[ID][\"path\"];\n")
	out.WriteString("};\n\n")
	out.WriteString("export interface OpenAPIClientTransport {\n")
	out.WriteString("    request<ID extends OpenAPIOperationId>(input: OpenAPIClientTransportInput<ID>): Promise<OpenAPIClientResponse<ID>>;\n")
	out.WriteString("}\n\n")
	out.WriteString("export type OpenAPIClient = {\n")
	out.WriteString("    [ID in OpenAPIOperationId]: (input?: OpenAPIClientInput<ID>) => Promise<OpenAPIClientResponse<ID>>;\n")
	out.WriteString("};\n\n")
	out.WriteString("export function createOpenAPIClient(transport: OpenAPIClientTransport): OpenAPIClient {\n")
	out.WriteString("    return {\n")
	for _, op := range ops {
		out.WriteString("        ")
		out.WriteString(quote(op.OperationID))
		out.WriteString(": (input) => transport.request({ operationId: ")
		out.WriteString(quote(op.OperationID))
		out.WriteString(", method: ")
		out.WriteString(quote(op.Method))
		out.WriteString(", path: ")
		out.WriteString(quote(op.Path))
		out.WriteString(", ...input }),\n")
	}
	out.WriteString("    } as OpenAPIClient;\n")
	out.WriteString("}\n")
	return out.Bytes()
}

func asMap(value any) map[string]any {
	if out, ok := value.(map[string]any); ok {
		return out
	}
	return map[string]any{}
}

func stringValue(value any) string {
	if out, ok := value.(string); ok {
		return strings.TrimSpace(out)
	}
	return ""
}

func isHTTPMethod(method string) bool {
	switch method {
	case "GET", "POST", "PUT", "PATCH", "DELETE":
		return true
	default:
		return false
	}
}

func quote(value string) string {
	return strconv.Quote(value)
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
